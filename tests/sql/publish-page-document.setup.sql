-- Disposable PostgreSQL fixture for the atomic page-publication migration.
-- This is an isolated CI database, not a production schema migration.

do $roles$
begin
  if not exists (select 1 from pg_roles where rolname = 'anon') then
    create role anon nologin;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'authenticated') then
    create role authenticated nologin;
  end if;
  if not exists (select 1 from pg_roles where rolname = 'service_role') then
    create role service_role nologin;
  end if;
end
$roles$;

create schema auth;
create table auth.users (
  id uuid primary key
);
create function auth.uid()
returns uuid
language sql
stable
as $function$
  select nullif(current_setting('request.jwt.claim.sub', true), '')::uuid
$function$;

create function auth.jwt()
returns jsonb
language sql
stable
as $function$
  select coalesce(nullif(current_setting('request.jwt.claims', true), ''), '{}')::jsonb
$function$;

grant usage on schema auth to anon, authenticated, service_role;
grant execute on function auth.uid() to authenticated;
grant execute on function auth.jwt() to anon, authenticated, service_role;
grant usage on schema public to anon, authenticated, service_role;

create table public.cms_sections (
  id uuid primary key default gen_random_uuid(),
  page text not null,
  section_key text not null,
  content jsonb,
  draft_content jsonb,
  status text not null default 'draft',
  version integer not null default 0,
  updated_at timestamptz not null default now(),
  constraint cms_sections_page_section_key_unique unique (page, section_key)
);

create table public.cms_revisions (
  id bigint generated by default as identity primary key,
  section_id uuid not null references public.cms_sections(id) on delete cascade,
  content jsonb not null,
  version integer not null,
  saved_at timestamptz not null default now(),
  constraint cms_revisions_section_version_unique unique (section_id, version)
);

alter table public.cms_sections enable row level security;
alter table public.cms_revisions enable row level security;

create policy cms_sections_authenticated_all
  on public.cms_sections
  for all
  to authenticated
  using (true)
  with check (true);

create policy cms_revisions_authenticated_all
  on public.cms_revisions
  for all
  to authenticated
  using (true)
  with check (true);

grant select, insert, update on public.cms_sections to authenticated;
grant select, insert on public.cms_revisions to authenticated;
grant usage, select on sequence public.cms_revisions_id_seq to authenticated;
