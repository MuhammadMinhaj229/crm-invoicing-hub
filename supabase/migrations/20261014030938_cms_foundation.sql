-- Safar Studio CMS foundation. Applies only to website CMS tables, not the
-- removed CRM schema. Editor authorization uses server-controlled Supabase Auth
-- app_metadata.cms_role (owner | admin | editor), never user-editable metadata.
begin;

create table if not exists public.cms_sections (
  id uuid primary key default gen_random_uuid(),
  page text not null,
  section_key text not null,
  content jsonb,
  draft_content jsonb,
  status text not null default 'draft',
  version integer not null default 0,
  updated_at timestamptz not null default now()
);

alter table public.cms_sections
  add column if not exists draft_content jsonb,
  add column if not exists status text not null default 'draft',
  add column if not exists version integer not null default 0,
  add column if not exists updated_at timestamptz not null default now();

do $migration$
begin
  if (
    select count(*)
      from information_schema.columns
     where table_schema = 'public'
       and table_name = 'cms_sections'
       and column_name in ('id', 'page', 'section_key', 'content')
  ) <> 4 then
    raise exception 'cms_sections is incompatible: expected id, page, section_key and content columns. Inspect the existing schema before migrating.';
  end if;
end
$migration$;

-- Duplicate legacy page keys intentionally stop this migration instead of
-- silently choosing which page becomes authoritative.
create unique index if not exists cms_sections_page_section_key_uidx
  on public.cms_sections (page, section_key);

create table if not exists public.cms_revisions (
  id bigint generated by default as identity primary key,
  section_id uuid not null references public.cms_sections(id) on delete cascade,
  content jsonb not null,
  version integer not null,
  saved_at timestamptz not null default now()
);

do $migration$
begin
  if (
    select count(*)
      from information_schema.columns
     where table_schema = 'public'
       and table_name = 'cms_revisions'
       and column_name in ('id', 'section_id', 'content', 'version', 'saved_at')
  ) <> 5 then
    raise exception 'cms_revisions is incompatible: expected id, section_id, content, version and saved_at columns. Inspect the existing schema before migrating.';
  end if;
end
$migration$;

create unique index if not exists cms_revisions_section_version_uidx
  on public.cms_revisions (section_id, version);
create index if not exists cms_revisions_section_version_order_idx
  on public.cms_revisions (section_id, version desc);

alter table public.cms_sections enable row level security;
alter table public.cms_revisions enable row level security;

-- Remove the broad policy used by earlier generic CMS test schemas.
drop policy if exists cms_sections_authenticated_all on public.cms_sections;
drop policy if exists cms_revisions_authenticated_all on public.cms_revisions;

drop policy if exists cms_sections_read_published_or_editor on public.cms_sections;
drop policy if exists cms_sections_read_scope_guard on public.cms_sections;
drop policy if exists cms_sections_editor_insert on public.cms_sections;
drop policy if exists cms_sections_editor_insert_guard on public.cms_sections;
drop policy if exists cms_sections_editor_update on public.cms_sections;
drop policy if exists cms_sections_editor_update_guard on public.cms_sections;
drop policy if exists cms_revisions_editor_read on public.cms_revisions;
drop policy if exists cms_revisions_editor_read_guard on public.cms_revisions;
drop policy if exists cms_revisions_editor_insert on public.cms_revisions;
drop policy if exists cms_revisions_editor_insert_guard on public.cms_revisions;

create policy cms_sections_read_published_or_editor on public.cms_sections
  for select to anon, authenticated
  using (
    status = 'published'
    or coalesce(auth.jwt() -> 'app_metadata' ->> 'cms_role', '') in ('owner', 'admin', 'editor')
  );
-- Restrictive guards ensure older broad permissive policies cannot expose drafts.
create policy cms_sections_read_scope_guard on public.cms_sections as restrictive
  for select to anon, authenticated
  using (
    status = 'published'
    or coalesce(auth.jwt() -> 'app_metadata' ->> 'cms_role', '') in ('owner', 'admin', 'editor')
  );
create policy cms_sections_editor_insert on public.cms_sections
  for insert to authenticated
  with check (coalesce(auth.jwt() -> 'app_metadata' ->> 'cms_role', '') in ('owner', 'admin', 'editor'));
create policy cms_sections_editor_insert_guard on public.cms_sections as restrictive
  for insert to authenticated
  with check (coalesce(auth.jwt() -> 'app_metadata' ->> 'cms_role', '') in ('owner', 'admin', 'editor'));
create policy cms_sections_editor_update on public.cms_sections
  for update to authenticated
  using (coalesce(auth.jwt() -> 'app_metadata' ->> 'cms_role', '') in ('owner', 'admin', 'editor'))
  with check (coalesce(auth.jwt() -> 'app_metadata' ->> 'cms_role', '') in ('owner', 'admin', 'editor'));
create policy cms_sections_editor_update_guard on public.cms_sections as restrictive
  for update to authenticated
  using (coalesce(auth.jwt() -> 'app_metadata' ->> 'cms_role', '') in ('owner', 'admin', 'editor'))
  with check (coalesce(auth.jwt() -> 'app_metadata' ->> 'cms_role', '') in ('owner', 'admin', 'editor'));

create policy cms_revisions_editor_read on public.cms_revisions
  for select to authenticated
  using (coalesce(auth.jwt() -> 'app_metadata' ->> 'cms_role', '') in ('owner', 'admin', 'editor'));
create policy cms_revisions_editor_read_guard on public.cms_revisions as restrictive
  for select to authenticated
  using (coalesce(auth.jwt() -> 'app_metadata' ->> 'cms_role', '') in ('owner', 'admin', 'editor'));
create policy cms_revisions_editor_insert on public.cms_revisions
  for insert to authenticated
  with check (coalesce(auth.jwt() -> 'app_metadata' ->> 'cms_role', '') in ('owner', 'admin', 'editor'));
create policy cms_revisions_editor_insert_guard on public.cms_revisions as restrictive
  for insert to authenticated
  with check (coalesce(auth.jwt() -> 'app_metadata' ->> 'cms_role', '') in ('owner', 'admin', 'editor'));

revoke all privileges on table public.cms_sections from public, anon, authenticated;
revoke all privileges on table public.cms_revisions from public, anon, authenticated;
grant select on table public.cms_sections to anon, authenticated;
grant insert, update on table public.cms_sections to authenticated;
grant select, insert on table public.cms_revisions to authenticated;

do $migration$
begin
  if to_regclass('public.cms_revisions_id_seq') is not null then
    execute 'grant usage, select on sequence public.cms_revisions_id_seq to authenticated';
  end if;
end
$migration$;

comment on table public.cms_sections is 'Safar Studio website documents. Only published rows are public; draft access is editor-restricted.';
comment on table public.cms_revisions is 'Immutable publication snapshots for Safar Studio; editor-restricted.';
commit;
